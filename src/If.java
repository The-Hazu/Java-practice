public class If {
    public static void main(String[] args) {
        int a = 9;
        if (a < 5) {
            System.out.println("a меньше 5");
        } else if (a < 10) {
            System.out.println("a меньше 10");
        }  else {
            System.out.println("Больше и 5 и 10");
        }
    }
}
